class Solution {
    public Node insertAtEnd(Node head, int x) {
        Node node = new Node(x);
        
        if(head == null) return node;
        
        Node pointer = head;
        while(pointer.next != null){
            pointer = pointer.next;
        }
        
        pointer.next = node;
        
        return head;
    }
}

